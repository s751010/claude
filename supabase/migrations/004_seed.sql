insert into plan_limits (plan, max_menus, max_dishes, allow_ai) values
  ('growth', 3,    100,  true),
  ('pro',    null, null, true)
on conflict (plan) do update
  set max_menus  = excluded.max_menus,
      max_dishes = excluded.max_dishes,
      allow_ai   = excluded.allow_ai,
      updated_at = now();


